#include ".build/AlgorithmRegistry.hpp"
#include "Algorithms/TraceRunner.hpp"
#include "DataStructures/Grid.hpp"
#include "Output/JsonWriter.hpp"

#include <exception>
#include <iostream>
#include <string>
#include <utility>

int main() {
    try {
        using CellValue = int; // Change to std::string for text values.
        // Edit these rows, then press Ctrl+Shift+B in VS Code.
        // S = start, G = goal, # = wall, . = open cell.
        Grid<CellValue> grid({
            "S.............",
            ".####.#####...",
            "....#.....#...",
            "###.#.###.#.#.",
            "....#...#...#.",
            ".######.#####.",
            ".............G",
        });

        // Generated by build-and-run.ps1 from the headers in Algorithms/.
        auto searches = makeAlgorithms<CellValue>();
        std::vector<std::pair<std::string, std::string>> manifest;
        for (auto& [id, algorithm] : searches) {
            const std::string filename = "web/run-" + id + ".json";
            Node<CellValue>* first = id == "algo1"
                ? runWithExpansionTrace(*algorithm, grid,
                                        static_cast<std::size_t>(grid.getNodeCount()) * 4)
                : algorithm->run(grid);
            JsonWriter::write(filename, grid, algorithm->getName());
            manifest.emplace_back(id, algorithm->getName());
            std::cout << algorithm->getName() << " wrote " << filename << ": ";
            if (first == nullptr && grid.wasGoalExpanded()) {
                std::cout << "goal reached, but prev links contain a cycle\n";
            } else if (first == nullptr) std::cout << "no path found\n";
            else std::cout << grid.getPathLength() << " steps\n";
        }
        JsonWriter::writeManifest("web/algorithms.json", manifest);
    } catch (const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
